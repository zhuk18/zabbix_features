#!/usr/bin/env python3
"""Writes the code copies of normalization/port-name-forms.tsv (topology-6-normalization.md §4.6) into ingest/TopologyNormalize.php (the only place that decides), between the markers
`BEGIN port-name-forms.tsv` / `END port-name-forms.tsv`: database/topology/discovery/ingest/TopologyNormalize.php (a constant).
The table is sorted longest long form first (the first match wins). The native step and push.py do not use it (handoff 025: the step extracts, ingest decides).

  gen_port_name_forms.py [--spec PATH] [--check]

--check changes nothing: it exits 1 if a code copy differs from the file (test_normalization uses it). The spec file is read-only; its default place is
/media/sf_topology-specs/normalization/port-name-forms.tsv (TOPOLOGY_NORMALIZATION_FORMS overrides it). Handoff 025.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SPEC = os.environ.get("TOPOLOGY_NORMALIZATION_FORMS", "/media/sf_topology-specs/normalization/port-name-forms.tsv")
FILES = {
    "php": os.path.join(HERE, "ingest", "TopologyNormalize.php"),
}
BEGIN, END = "BEGIN port-name-forms.tsv", "END port-name-forms.tsv"
SPEC_NAMES = os.environ.get("TOPOLOGY_NORMALIZATION_NAMES", "/media/sf_topology-specs/normalization/default-names.tsv")
BEGIN_NAMES, END_NAMES = "BEGIN default-names.tsv", "END default-names.tsv"      # normalization §4.10 (task 074): the same file, the same marker pair, a second block


def read_table(path):
    rows = []
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        long_form, short_form = line.rstrip("\n").split("\t")
        rows.append((long_form, short_form))
    return sorted(rows, key=lambda r: (-len(r[0]), r[0]))


def read_names(path):
    """default-names.tsv: (kind, value) of every row; the first row is the header. The value is compared after the device name key (model 6.7.1), so it is lower case here."""
    rows = []
    for n, line in enumerate(open(path, encoding="utf-8")):
        if n == 0 or line.startswith("#") or not line.strip():
            continue
        cols = line.rstrip("\n").split("\t")
        rows.append((cols[2], cols[1].lower() if cols[2] == "exact" else cols[1]))
    return rows


def block_names(rows):
    head = "generated by database/topology/discovery/gen_port_name_forms.py from normalization/default-names.tsv; do not edit"
    body = "".join("\t['%s', '%s'],\n" % (k, v.replace("\\", "\\\\").replace("'", "\\'")) for k, v in rows)
    return "// %s (%s)\nconst TOPO_DEFAULT_NAMES = [\n%s];\n// %s\n" % (BEGIN_NAMES, head, body, END_NAMES)


def block(kind, rows):
    head = "generated by database/topology/discovery/gen_port_name_forms.py from normalization/port-name-forms.tsv; do not edit"
    if kind == "c":
        body = "".join('\t{"%s", "%s"},\n' % r for r in rows)
        return ("/* %s (%s) */\n"
                "static const struct\n{\n\tconst char\t*long_form;\n\tconst char\t*short_form;\n}\n"
                "topo_port_forms[] =\n{\n%s\t{NULL, NULL}\n};\n/* %s */\n") % (BEGIN, head, body, END)
    if kind == "py":
        body = "".join('    ("%s", "%s"),\n' % r for r in rows)
        return "# %s (%s)\nPORT_NAME_FORMS = (\n%s)\n# %s\n" % (BEGIN, head, body, END)
    body = "".join("\t['%s', '%s'],\n" % r for r in rows)
    return "// %s (%s)\nconst TOPO_PORT_NAME_FORMS = [\n%s];\n// %s\n" % (BEGIN, head, body, END)


def current(kind, text, begin=BEGIN, end=END):
    m = re.search(r"^(?:/\*|#|//) %s[^\n]*\n.*?^(?:/\*|#|//) %s[^\n]*\n" % (re.escape(begin), re.escape(end)), text, re.S | re.M)
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", default=SPEC)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--names", default=SPEC_NAMES)
    a = ap.parse_args()
    rows = read_table(a.spec)
    name_rows = read_names(a.names) if os.path.exists(a.names) else None
    bad = 0
    for kind, path, begin, end, want in [(k, p, BEGIN, END, block(k, rows)) for k, p in FILES.items()] + \
            ([("php", FILES["php"], BEGIN_NAMES, END_NAMES, block_names(name_rows))] if name_rows is not None else []):
        text = open(path, encoding="utf-8").read()
        m = current(kind, text, begin, end)
        if m is None:
            print("%s: no block between the markers" % path)
            bad += 1
        elif m.group(0) != want:
            bad += 1
            if a.check:
                print("%s: the code copy differs from %s" % (path, a.spec))
            else:
                open(path, "w", encoding="utf-8").write(text[:m.start()] + want + text[m.end():])
                print("%s: rewritten" % path)
        elif not a.check:
            print("%s: already current" % path)
    return 1 if bad and a.check else (1 if bad and not a.check and any(current(k, open(p).read()) is None for k, p in FILES.items()) else 0)


if __name__ == "__main__":
    sys.exit(main())
