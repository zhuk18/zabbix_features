#!/usr/bin/env python3
"""Writes the code copies of normalization/port-name-forms.tsv (topology-6-normalization.md §4.6) into the three implementations, between the markers
`BEGIN port-name-forms.tsv` / `END port-name-forms.tsv`:
  src/libs/zbxpreproc/preproc_topology.c  (a C table)      database/topology/discovery/push.py  (a tuple)      database/topology/discovery/ingest.php  (a constant)
The table is sorted longest long form first in all three (the first match wins).

  gen_port_name_forms.py [--spec PATH] [--check]

--check changes nothing: it exits 1 if a code copy differs from the file (test_normalization uses it). The spec file is read-only; its default place is
/media/sf_topology-specs/normalization/port-name-forms.tsv (TOPOLOGY_NORMALIZATION_FORMS overrides it). Handoff 025.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SPEC = os.environ.get("TOPOLOGY_NORMALIZATION_FORMS", "/media/sf_topology-specs/normalization/port-name-forms.tsv")
FILES = {
    "c": os.path.join(REPO, "src", "libs", "zbxpreproc", "preproc_topology.c"),
    "py": os.path.join(HERE, "push.py"),
    "php": os.path.join(HERE, "ingest.php"),
}
BEGIN, END = "BEGIN port-name-forms.tsv", "END port-name-forms.tsv"


def read_table(path):
    rows = []
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        long_form, short_form = line.rstrip("\n").split("\t")
        rows.append((long_form, short_form))
    return sorted(rows, key=lambda r: (-len(r[0]), r[0]))


def block(kind, rows):
    head = "generated by database/topology/discovery/gen_port_name_forms.py from normalization/port-name-forms.tsv; do not edit"
    if kind == "c":
        body = "".join('\t{"%s", "%s"},\n' % r for r in rows)
        return ("/* %s (%s) */\n"
                "static const struct\n{\n\tconst char\t*long_form;\n\tconst char\t*short_form;\n}\n"
                "topo_port_forms[] =\n{\n%s\t{NULL, NULL}\n};\n/* %s */\n") % (BEGIN, head, body, END)
    if kind == "py":
        body = "".join('    ("%s", "%s"),\n' % r for r in rows)
        return "# %s (%s)\nPORT_NAME_FORMS = (\n%s)\n# %s\n" % (BEGIN, head, body, END)
    body = "".join("\t['%s', '%s'],\n" % r for r in rows)
    return "// %s (%s)\nconst TOPO_PORT_NAME_FORMS = [\n%s];\n// %s\n" % (BEGIN, head, body, END)


def current(kind, text):
    m = re.search(r"^(?:/\*|#|//) %s[^\n]*\n.*?^(?:/\*|#|//) %s[^\n]*\n" % (re.escape(BEGIN), re.escape(END)), text, re.S | re.M)
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", default=SPEC)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows = read_table(a.spec)
    bad = 0
    for kind, path in FILES.items():
        text = open(path, encoding="utf-8").read()
        m = current(kind, text)
        want = block(kind, rows)
        if m is None:
            print("%s: no block between the markers" % path)
            bad += 1
        elif m.group(0) != want:
            bad += 1
            if a.check:
                print("%s: the code copy differs from %s" % (path, a.spec))
            else:
                open(path, "w", encoding="utf-8").write(text[:m.start()] + want + text[m.end():])
                print("%s: rewritten" % path)
        elif not a.check:
            print("%s: already current" % path)
    return 1 if bad and a.check else (1 if bad and not a.check and any(current(k, open(p).read()) is None for k, p in FILES.items()) else 0)


if __name__ == "__main__":
    sys.exit(main())
